// Reviewed behavior metadata. The generator resolves every export against emitted
// public declarations and rejects missing mappings rather than inventing an API.
// `behavior` fills the reference only where an export has no JSDoc of its own;
// `limitations` fills the Limits column. Both also feed the starter template's
// framework table. Describe Satin's own exports in plain words.
