import { generateReference, referenceInventory } from './api-reference.mjs'
import { apiBehaviors, frameworkExtensions } from './api-behaviors.mjs'
import { publicDeclarationGraph } from './api-graph.mjs'
import { SymbolFlags, NodeBuilderFlags } from 'typescript/unstable/sync'
import { openDeclarationProject, printDeclaration } from './native-api.mjs'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const write = process.argv.includes('--write')
const project = openDeclarationProject(resolve(root, 'dist/index.d.ts'))
try {
  const { program, checker, emitter } = project
  const file = program.getSourceFile(resolve(root, 'dist/index.d.ts'))
  const symbols = checker
    .getExportsOfModule(checker.getSymbolAtLocation(file))
    .sort((a, b) => a.name.localeCompare(b.name))
  const entries = symbols.map(symbol => {
    const target = symbol.flags & SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
    const declarations = (target.declarations ?? []).map(handle => handle.resolve())
    const value = !!(target.flags & SymbolFlags.Value)
    const declaration = declarations.map(node => printDeclaration(emitter, node)).join('\n')
    const type = checker.typeToString(
      value
        ? checker.getTypeOfSymbolAtLocation(target, declarations[0])
        : checker.getDeclaredTypeOfSymbol(target),
      undefined,
      NodeBuilderFlags.NoTruncation | NodeBuilderFlags.InTypeAlias,
    )
    return { name: symbol.name, value, declaration, type }
  })
  const counts = `${entries.filter(e => e.value).length} values; ${entries.filter(e => !e.value).length} type-only exports`
  const graph = publicDeclarationGraph(project, resolve(root, 'dist/index.d.ts'))
  const report =
    `# satin API\n\nGenerated by api-report.mjs from the emitted declarations. ${counts}.\n\n` +
    entries
      .map(
        e =>
          `## ${e.name}\n\n${e.value ? 'Value' : 'Type'}\n\n\`\`\`ts\n${e.declaration}\n// Resolved: ${e.type}\n\`\`\`\n`,
      )
      .join('\n') +
    `\n## Transitive public declaration graph\n\nMenuProps.trigger is experimental. All reachable local signature declarations follow, including utility-type dependencies. External library types remain named references.\n\n\`\`\`ts\n${graph}\n\`\`\`\n`
  async function output(path, content) {
    // Module-scoped declaration names carry absolute paths; keep the report checkout-independent.
    content = content.replaceAll(root + '/', '')
    if (write) {
      await mkdir(dirname(path), { recursive: true })
      await writeFile(path, content)
    } else if ((await readFile(path, 'utf8').catch(() => '')) !== content)
      throw new Error(`${path} is stale. Run pnpm --filter @satinhq/kit api:write after building.`)
  }
  await output(resolve(root, 'api/satin.api.md'), report)
  const groups = [
    [
      'App and navigation',
      'defineApp runApp defineRoutes route param defineNavigation Screen NavigationStack NavigationLink TabView',
    ],
    [
      'Lists and controls',
      'List Form Section Button Toggle Picker TextField TextEditor ContentUnavailableView',
    ],
    ['Device capabilities', 'PhotosPicker FileImporter ShareLink PasteButton'],
    ['Layout and text', 'Text Label Selectable VStack HStack ZStack Spacer Divider ScrollView'],
    ['Presentation', 'Sheet Alert ConfirmationDialog Menu ContextMenu'],
    ['Animation', 'withAnimation Animation'],
    ['Glass and imagery', 'Glass GlassEffect GlassEffectContainer SymbolImage Image'],
    [
      'Data and environment',
      'defineResource useResource defineDatabase collection useQuery useRecord useAppStorage useSceneStorage useNotifications useReachability',
    ],
  ]
  const available = new Set(entries.map(entry => entry.name))
  const inventory =
    '<!-- public-api:start -->\n| Area | Start here |\n| --- | --- |\n' +
    groups
      .map(
        ([label, names]) =>
          `| ${label} | ${names
            .split(' ')
            .filter(name => available.has(name))
            .map(name => `\`${name}\``)
            .join(', ')} |`,
      )
      .join('\n') +
    '\n\nSee the packaged API reference for every export, prop and limitation.\n<!-- public-api:end -->'
  for (const relative of ['README.md', '../../docs/getting-started.md']) {
    const path = resolve(root, relative),
      source = await readFile(path, 'utf8')
    await output(
      path,
      source.replace(/<!-- public-api:start -->[\s\S]*?<!-- public-api:end -->/, inventory),
    )
  }
  const path = resolve(root, '../../templates/basic/AGENTS.md'),
    source = await readFile(path, 'utf8')
  // Reuse the reviewed concept metadata and emitted declarations. Never maintain
  // a second behavior catalogue in the consumer template.
  const { inventory: referenceEntries } = await referenceInventory(root)
  const concepts = [...apiBehaviors, ...frameworkExtensions].filter(
    concept => concept.exports.length,
  )
  const covered = new Set(concepts.flatMap(concept => concept.exports))
  const missing = entries.filter(entry => entry.value && !covered.has(entry.name))
  if (missing.length)
    throw new Error(`Consumer guidance missing: ${missing.map(entry => entry.name).join(', ')}`)
  const cell = text => text.replaceAll('|', '\\|').replaceAll('\n', ' ')
  const declarationLink = name => {
    const entry = referenceEntries.find(
      entry => entry.module === '@satinhq/kit' && entry.name === name,
    )
    if (!entry) throw new Error(`Consumer guidance names an unavailable export: ${name}`)
    const declaration = entry.declaration.replace(/^\.\.\//, 'node_modules/@satinhq/kit/dist/')
    return `[\`${name}\`](${declaration})`
  }
  const table = [
    '<!-- framework-api:start -->',
    'Generated from the same reviewed metadata as the shipped Satin API reference. Links open the exact package declarations; related type-only exports are listed in that reference.',
    '',
    '| Satin exports and declarations | Behavior and ownership | Limits |',
    '| --- | --- | --- |',
    ...concepts.map(
      concept =>
        `| ${concept.exports.map(declarationLink).join(', ')} | ${cell(concept.behavior)} | ${cell(concept.limitations)} |`,
    ),
    '<!-- framework-api:end -->',
  ].join('\n')
  await output(
    path,
    source.replace(/<!-- framework-api:start -->[\s\S]*?<!-- framework-api:end -->/, table),
  )
  await generateReference(write)
  console.log(`API report: ${counts}; docs and template table match.`)
} finally {
  project.close()
}
