import { describe, expect, it } from 'vitest'
import {
  measuredMinimizeProgress,
  minimizePlacement,
  TabMinimizeIntent,
} from './tabMinimizeMotion.ts'

describe('native minimizing intent', () => {
  it('restores compact bottom tabs when their placement becomes top', () => {
    const intent = new TabMinimizeIntent()
    intent.beginGesture(0)
    expect(intent.observe(200, 1000, 'bottom')).toBe('collapse')
    expect(intent.observe(200, 1000, 'top')).toBe('restore')
    expect(intent.compact).toBe(false)
    expect(intent.observe(400, 1000, 'top')).toBeUndefined()
  })
  it('keeps top tabs expanded through scrolling, navigation and resume', () => {
    const intent = new TabMinimizeIntent()
    intent.beginGesture(0)
    expect(intent.observe(200, 1000, 'top')).toBeUndefined()
    expect(intent.compact).toBe(false)
    intent.rebase(0)
    intent.beginGesture(0)
    expect(intent.observe(300, 1000, 'top')).toBeUndefined()
    intent.endGesture()
    expect(intent.observe(300, 1000, 'top')).toBeUndefined()
    expect(intent.compact).toBe(false)
    // Bottom placement retains the measured phone behavior.
    intent.beginGesture(0)
    expect(intent.observe(200, 1000, 'bottom')).toBe('collapse')
  })

  it('ignores a small drag and reversal, then triggers once after the measured dead zone', () => {
    const intent = new TabMinimizeIntent()
    intent.beginGesture()
    expect(intent.observe(40, 1000)).toBeUndefined()
    expect(intent.observe(20, 1000)).toBeUndefined()
    expect(intent.observe(80, 1000)).toBeUndefined()
    expect(intent.observe(90, 1000)).toBe('collapse')
    expect(intent.observe(400, 1000)).toBeUndefined()
    expect(intent.observe(170, 1000)).toBeUndefined()
    expect(intent.observe(0, 1000)).toBe('restore')
  })
  it('rearms from a restored position and rejects bounce accumulation', () => {
    const intent = new TabMinimizeIntent()
    intent.beginGesture()
    intent.observe(80, 1000)
    intent.restore(500)
    intent.beginGesture()
    expect(intent.observe(550, 1000)).toBeUndefined()
    expect(intent.observe(580, 1000)).toBe('collapse')
    expect(intent.observe(1010, 1000)).toBeUndefined()
    expect(intent.compact).toBe(true)
    intent.beginGesture()
    expect(intent.observe(1010, 1000)).toBe('restore')
    expect(intent.observe(1000, 1000)).toBeUndefined()
  })
  it('keeps a short-content collapse compact through its own bottom bounce', () => {
    const intent = new TabMinimizeIntent()
    intent.beginGesture()
    expect(intent.observe(80, 180)).toBe('collapse')
    expect(intent.observe(212, 180)).toBeUndefined()
    expect(intent.observe(180, 180)).toBeUndefined()
    expect(intent.compact).toBe(true)
    intent.beginGesture()
    expect(intent.observe(220, 180)).toBe('restore')
    expect(intent.compact).toBe(false)
  })
  it('does not collapse again from momentum after a restore tap', () => {
    const intent = new TabMinimizeIntent()
    intent.beginGesture()
    intent.observe(80, 1000)
    intent.restore(110)
    expect(intent.observe(175, 1000)).toBeUndefined()
    expect(intent.observe(300, 1000)).toBeUndefined()
    intent.beginGesture()
    expect(intent.observe(380, 1000)).toBe('collapse')
  })
  it('retains measured overshoot and lands on the native compact geometry', () => {
    expect(measuredMinimizeProgress('collapse', 240)).toBeGreaterThan(1)
    expect(measuredMinimizeProgress('collapse', 900)).toBe(1)
    expect(minimizePlacement(1)).toEqual({ x: 7, y: 7, width: 48, height: 48, progress: 1 })
    for (const direction of ['collapse', 'restore'] as const) {
      for (let t = 0; t <= 850; t++)
        expect(Number.isFinite(measuredMinimizeProgress(direction, t))).toBe(true)
    }
  })
})

it('does not interpret restored offsets or a new tab as a downward gesture', () => {
  const intent = new TabMinimizeIntent()
  expect(intent.observe(240, 1000)).toBeUndefined()
  expect(intent.compact).toBe(false)
  intent.beginGesture(240)
  intent.endContact()
  expect(intent.observe(310, 1000)).toBeUndefined()
  intent.beginGesture()
  expect(intent.observe(350, 1000)).toBeUndefined()
  intent.rebase(90)
  expect(intent.observe(180, 1000)).toBeUndefined()
  expect(intent.compact).toBe(false)
  intent.beginGesture()
  expect(intent.observe(250, 1000)).toBe('collapse')
  intent.restore(250)
  intent.beginGesture()
  expect(intent.observe(270, 1000)).toBeUndefined()
  intent.endContact()
  expect(intent.observe(320, 1000)).toBe('collapse')
  intent.restore(320)
  intent.endGesture()
  expect(intent.observe(500, 1000)).toBeUndefined()
  intent.beginGesture(500)
  intent.endContact(570)
  expect(intent.observe(570, 1000)).toBe('collapse')
})
