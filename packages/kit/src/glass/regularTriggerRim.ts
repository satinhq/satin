export function regularTriggerRimResponse(
  luminance: number,
  appearance: 'light' | 'dark',
  regime: 0 | 1,
) {
  const knots = REGULAR_TRIGGER_RIM_CURVES[`${appearance}-${regime}`]
  const next = knots.findIndex(q => q.context >= luminance)
  if (next <= 0) return [...knots[next === 0 ? 0 : knots.length - 1].strength]
  const a = knots[next - 1],
    b = knots[next]
  const mix = (luminance - a.context) / (b.context - a.context)
  return a.strength.map((v, i) => v + (b.strength[i] - v) * mix)
}
